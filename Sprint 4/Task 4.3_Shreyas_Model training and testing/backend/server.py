"""
=============================================================================
TASK 4.3: REST API SERVER FOR MODEL TRAINING (STRICT SCOPE)
=============================================================================
"""
from flask import Flask, request, jsonify
from flask_cors import CORS
from model_trainer import ModelTrainerEngine

app = Flask(__name__)
# Allow cross-origin requests from the React frontend
CORS(app) 

# Initialize the core engine that handles .fit() and .predict()
engine = ModelTrainerEngine(splits_dir="splits", models_dir="models", results_dir="results")

@app.route('/api/train', methods=['POST'])
def train_model():
    """
    API Endpoint to trigger model training.
    Acts as a pure receiver for data generated by Teammate D (Task 4.1) 
    and Teammate A (Task 4.2).
    """
    try:
        # Parse incoming JSON payload
        data = request.get_json()
        if not data:
            return jsonify({"status": "error", "message": "No payload provided."}), 400

        # Extract variables provided by upstream tasks
        task_type = data.get('task_type')
        model_name = data.get('model_name')
        hyperparameters = data.get('hyperparameters', {})

        # Validate that upstream tasks actually sent the required data
        if not task_type or not model_name:
            return jsonify({"status": "error", "message": "Missing task_type or model_name from upstream tasks."}), 400

        # Trigger the core Task 4.3 engine: .fit() and .predict()
        result = engine.train_and_predict(
            task_type=task_type,
            model_name=model_name,
            hyperparameters=hyperparameters
        )

        # Return the execution telemetry back to the React frontend
        return jsonify(result), 200

    except Exception as e:
        # Fallback error handling to prevent server crashes and send safe message to UI
        return jsonify({"status": "error", "message": str(e)}), 400

if __name__ == '__main__':
    app.run(port=5000, debug=True)